import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fetchJson, generatedModuleMap, officialCatalogVariants, registryCss, serializeModuleMap, writeRegistryFiles } from './lib/registry-sync.mjs';

const projectRoot = path.resolve(import.meta.dirname, '..');
const outputRoot = path.join(projectRoot, 'ui-src/library-runtime/vendor/spell');
const manifestFile = path.join(projectRoot, 'ui-src/library-runtime/spell-registry.generated.ts');
const catalogManifestFile = path.join(projectRoot, 'src/spell-registry.generated.ts');
const cssFile = path.join(projectRoot, 'ui-src/library-runtime/spell-registry.generated.css');
const registry = await fetchJson('https://raw.githubusercontent.com/xxtomm/spell-ui/main/registry.json');
const files = new Map();
const dependencies = new Set();
const componentsWithoutChildren = new Set([
  'animated-checkbox', 'animated-gradient', 'bars-spinner', 'chart', 'color-selector', 'copy-button',
  'exploding-input', 'fallback-avatar', 'kbd', 'label-input', 'light-rays', 'qr-code', 'signature',
  'spinner', 'spotify-card', 'tweet'
]);

function rootExport(source) {
  const defaultName = source.match(/export\s+default\s+(?:function\s+)?([A-Z][A-Za-z0-9_]*)/)?.[1];
  if (defaultName) return 'default';
  return source.match(/export\s+(?:function|const)\s+([A-Z][A-Za-z0-9_]*)/)?.[1]
    ?? source.match(/export\s*\{\s*([A-Z][A-Za-z0-9_]*)/)?.[1];
}

const entries = await Promise.all(registry.items.filter((item) => item.type === 'registry:component').map(async (catalogItem) => {
  const item = await fetchJson(`https://spell.sh/r/${catalogItem.name}.json`);
  for (const dependency of item.dependencies ?? []) dependencies.add(dependency);
  const root = item.files?.find((file) => file.path.endsWith('.tsx'));
  if (!root || typeof root.content !== 'string') throw new Error(`Spell UI ${catalogItem.name} does not publish a TSX component.`);
  for (const file of item.files ?? []) if (typeof file.content === 'string') files.set(file.path, file.content);
  const exported = rootExport(root.content);
  if (!exported) throw new Error(`Unable to identify the Spell UI ${catalogItem.name} component export.`);
  return {
    slug: catalogItem.name,
    title: catalogItem.title ?? catalogItem.name,
    description: catalogItem.description ?? '',
    rootPath: `./vendor/spell/${root.path}`,
    rootExport: exported,
    previewPath: `./vendor/spell/${root.path}`,
    previewExport: exported,
    acceptsChildren: !componentsWithoutChildren.has(catalogItem.name),
    docsUrl: `https://spell.sh/docs/${catalogItem.name}`
  };
}));

files.set('lib/utils.ts', `import { clsx, type ClassValue } from "clsx";\nimport { twMerge } from "tailwind-merge";\nexport function cn(...inputs: ClassValue[]) { return twMerge(clsx(inputs)); }\n`);
await writeRegistryFiles({ outputRoot, files, alias: '@spell' });
const modules = generatedModuleMap(entries.map((entry) => entry.rootPath));
const generated = `// Generated by scripts/sync-spell-registry.mjs from the official MIT-licensed Spell UI registry.\n` +
  `import type { ReactRegistryEntry } from './types';\n` +
  `export const SPELL_REGISTRY_ENTRIES = ${JSON.stringify(entries, null, 2)} as const satisfies readonly ReactRegistryEntry[];\n` +
  `export const SPELL_REGISTRY_BY_SLUG = Object.fromEntries(SPELL_REGISTRY_ENTRIES.map((entry) => [entry.slug, entry])) as Record<string, ReactRegistryEntry>;\n` +
  `export const SPELL_REGISTRY_MODULES = ${serializeModuleMap(modules)};\n`;
await mkdir(path.dirname(manifestFile), { recursive: true });
await writeFile(manifestFile, generated, 'utf8');
const catalogVariants = officialCatalogVariants(entries, 'spell');
const catalogGenerated = `// Generated by scripts/sync-spell-registry.mjs from the official Spell UI registry.\n` +
  `import type { UiComponentVariant } from './ui-library.js';\n` +
  `export const SPELL_OFFICIAL_COMPONENT_VARIANTS = ${JSON.stringify(catalogVariants, null, 2)} as const satisfies Record<string, readonly UiComponentVariant[]>;\n`;
await writeFile(catalogManifestFile, catalogGenerated, 'utf8');
await writeFile(cssFile, registryCss(registry.items), 'utf8');
console.log(`Synced ${entries.length} Spell UI components and ${files.size} official source files.`);
console.log(`Runtime dependencies: ${[...dependencies].sort().join(', ')}`);
