function frontmatterValue(source, name) {
  return source.match(new RegExp(`^${name}:\\s*(.+)$`, 'm'))?.[1]?.trim() ?? '';
}

function normalizeLabel(value) {
  return value.replace(/`([^`]+)`/g, '$1').replace(/\s+/g, ' ').trim();
}

function officialHtml(value) {
  return value
    .replace(/\$\$/g, '')
    .replace(/\sautocomplete="off"/g, '')
    .trim();
}

function examplesFromMarkdown(slug, source) {
  const headings = [...source.matchAll(/^###\s+~(.+)$/gm)];
  return headings.map((heading, index) => {
    const section = source.slice(heading.index, headings[index + 1]?.index ?? source.length);
    const html = section.match(/```html\n([\s\S]*?)\n```/)?.[1];
    if (!html) throw new Error(`daisyUI ${slug} example ${index + 1} has no official HTML block.`);
    return {
      id: `${slug}-${index + 1}`,
      label: normalizeLabel(heading[1]),
      html: officialHtml(html),
    };
  });
}

async function loadEntry(slug) {
  const markdown = localSourceRoot
    ? await readFile(path.join(localSourceRoot, slug, '+page.md'), 'utf8')
    : await fetchText(`${sourceRoot}/${slug}/+page.md`);
  const demos = examplesFromMarkdown(slug, markdown);
  if (!demos.length) throw new Error(`daisyUI ${slug} has no official examples.`);
  return {
    slug,
    title: frontmatterValue(markdown, 'title') || slug,
    description: frontmatterValue(markdown, 'desc'),
    demos,
    layout: 'intrinsic',
    docsUrl: `https://daisyui.com/components/${slug}/`,
    ...presentationBySlug[slug]
  };
}

const entries = [];
for (let index = 0; index < slugs.length; index += 8) {
  entries.push(...await Promise.all(slugs.slice(index, index + 8).map(loadEntry)));
}

const runtimeEntries = entries.map((entry) => ({
  ...entry,
  demos: entry.demos.map(({ html: _html, ...demo }) => demo)
}));
const runtimeManifest = `// Generated by scripts/sync-daisyui-registry.mjs from the official MIT-licensed daisyUI v${version} documentation.\n` +
  `import type { DomRegistryEntry } from './types';\n` +
  `export const DAISYUI_REGISTRY_ENTRIES = ${JSON.stringify(runtimeEntries, null, 2)} as const satisfies readonly DomRegistryEntry[];\n` +
  `export const DAISYUI_REGISTRY_BY_SLUG = Object.fromEntries(DAISYUI_REGISTRY_ENTRIES.map((entry) => [entry.slug, entry])) as Record<string, DomRegistryEntry>;\n`;

const componentId = (slug) => slug.split('-').map((part) => part === '3d' ? '3D' : `${part[0].toUpperCase()}${part.slice(1)}`).join('');
const variants = Object.fromEntries(entries.map((entry) => [componentId(entry.slug), entry.demos.map((demo) => ({
  id: demo.id,
  label: demo.label,
  props: { registryDemo: demo.id }
}))]));
const catalogManifest = `// Generated by scripts/sync-daisyui-registry.mjs from the official daisyUI v${version} documentation.\n` +
  `import type { UiComponentVariant } from './ui-library.js';\n` +
  `export const DAISYUI_OFFICIAL_COMPONENT_VARIANTS = ${JSON.stringify(variants, null, 2)} as const satisfies Record<string, readonly UiComponentVariant[]>;\n`;

await mkdir(path.dirname(runtimeManifestFile), { recursive: true });
await rm(runtimeEntriesRoot, { recursive: true, force: true });
await mkdir(runtimeEntriesRoot, { recursive: true });
await Promise.all(entries.map((entry) => writeFile(
  path.join(runtimeEntriesRoot, `${entry.slug}.json`),
  `${JSON.stringify(entry, null, 2)}\n`,
  'utf8'
)));
await writeFile(runtimeManifestFile, runtimeManifest, 'utf8');
await writeFile(catalogManifestFile, catalogManifest, 'utf8');
console.log(`Synced ${entries.length} daisyUI components and ${entries.flatMap((entry) => entry.demos).length} official HTML examples from v${version}.`);
